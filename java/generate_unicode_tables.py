#!/usr/bin/env python3
"""Regenerate Java Unicode predicates from the exact deployed Rust tokenizer, never from the JDK."""
import argparse
import hashlib
import json
from pathlib import Path
import sys
import time


def ranges(values):
    """Represent sorted Unicode scalars as compact inclusive pairs."""
    result = []
    for value in values:
        if result and value == result[-1][1] + 1:
            result[-1][1] = value
        else:
            result.append([value, value])
    return result


def main():
    """Exhaustively query the pinned normalizer and pretokenizer once, then emit deterministic Java source."""
    parser = argparse.ArgumentParser()
    parser.add_argument("tokenizer", type=Path)
    parser.add_argument("output", type=Path)
    args = parser.parse_args()
    if sys.version_info[:2] != (3, 12):
        raise RuntimeError("PYTHON_VERSION_MISMATCH")
    import tokenizers
    from tokenizers import Tokenizer
    if tokenizers.__version__ != "0.23.3":
        raise RuntimeError("TOKENIZERS_VERSION_MISMATCH")
    expected = "48cea5d44424912a6fd1ea647bf4fe50b55ab8b1e5879c3275f80e339e8fae26"
    if hashlib.sha256(args.tokenizer.read_bytes()).hexdigest() != expected:
        raise RuntimeError("TOKENIZER_HASH_MISMATCH")
    tokenizer = Tokenizer.from_file(str(args.tokenizer))
    values = {name: [] for name in ("DROP", "SPACE", "CHINESE", "PUNCTUATION", "INPUT_SPACE")}
    started = time.monotonic()
    for cp in range(0x110000):
        if 0xd800 <= cp <= 0xdfff:
            continue
        char = chr(cp)
        normalized = tokenizer.normalizer.normalize_str(char)
        if normalized == "":
            values["DROP"].append(cp)
        elif normalized == " ":
            values["SPACE"].append(cp)
        elif normalized == " " + char + " ":
            values["CHINESE"].append(cp)
        elif normalized != char:
            raise RuntimeError("UNEXPECTED_NORMALIZATION_U+%04X" % cp)
        segments = tokenizer.pre_tokenizer.pre_tokenize_str("a" + char + "b")
        if [text for text, offsets in segments] == ["a", char, "b"]:
            values["PUNCTUATION"].append(cp)
        if char.isspace():
            values["INPUT_SPACE"].append(cp)
        if cp == 9999:
            print("FIRST_10000_SECONDS=%.3f" % (time.monotonic() - started), file=sys.stderr)
    tables = {name: ranges(points) for name, points in values.items()}
    digest = hashlib.sha256(json.dumps(tables, sort_keys=True, separators=(",", ":")).encode()).hexdigest()
    lines = ["package medaudit.pex;", "", "/** Generated by java/generate_unicode_tables.py from all Unicode scalar values.",
             " * Source: tokenizers 0.23.3 and tokenizer SHA-256 " + expected + ".",
             " * Table SHA-256: " + digest + ".",
             " * INPUT_SPACE separately matches Python " + ".".join(map(str, sys.version_info[:2])) + " str.isspace(), not BERT whitespace.",
             " * Do not replace these predicates with JDK Character categories: their Unicode versions differ.",
             " */", "public final class PinnedUnicode {"]
    for name, pairs in tables.items():
        lines.append("    private static final int[] " + name + " = {")
        flattened = ["0x%x" % cp for pair in pairs for cp in pair]
        for start in range(0, len(flattened), 12):
            lines.append("        " + ", ".join(flattened[start:start + 12]) + ("," if start + 12 < len(flattened) else ""))
        lines.append("    };")
    lines.extend(["", "    /** Find a scalar in immutable inclusive ranges with no JVM Unicode-version dependency. */",
                  "    private static boolean contains(int[] table, int cp) {",
                  "        int low = 0, high = table.length / 2 - 1;",
                  "        while (low <= high) {",
                  "            int mid = (low + high) >>> 1, start = table[mid * 2], end = table[mid * 2 + 1];",
                  "            if (cp < start) high = mid - 1; else if (cp > end) low = mid + 1; else return true;",
                  "        }",
                  "        return false;",
                  "    }", ""])
    for method, name in [("isDropped", "DROP"), ("isSpace", "SPACE"), ("isChinese", "CHINESE"), ("isPunctuation", "PUNCTUATION"), ("isInputSpace", "INPUT_SPACE")]:
        lines.extend(["    /** Query the pinned " + name.lower().replace("_", " ") + " scalar set. */",
                      "    public static boolean " + method + "(int cp) { return contains(" + name + ", cp); }"])
    lines.append("}")
    args.output.write_text("\n".join(lines) + "\n")
    print(json.dumps({"tokenizers": tokenizers.__version__, "scalar_count": 0x110000 - 0x800,
                      "elapsed_seconds": round(time.monotonic() - started, 3), "table_sha256": digest,
                      "range_counts": {name: len(pairs) for name, pairs in tables.items()}}))


if __name__ == "__main__":
    main()
